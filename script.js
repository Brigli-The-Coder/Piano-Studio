const WHATSAPP_NUMBER = '355682323772'; // international format, no + or leading zeros

function initContactForm() {
  const form = document.getElementById('contactForm');
  if (!form) return;

  form.addEventListener('submit', (e) => {
    e.preventDefault();

    const firstName = form.querySelector('#id_first_name')?.value.trim() || '';
    const lastName = form.querySelector('#id_last_name')?.value.trim() || '';
    const phone = form.querySelector('#id_phone_number')?.value.trim() || '';
    const message = form.querySelector('#id_message')?.value.trim() || '';

    const lines = [
      `Përshëndetje! Jam ${firstName} ${lastName}.`.trim(),
      phone ? `Telefoni im: ${phone}` : null,
      message ? `Mesazhi: ${message}` : null
    ].filter(Boolean);

    const text = encodeURIComponent(lines.join('\n'));
    const url = `https://wa.me/${WHATSAPP_NUMBER}?text=${text}`;
    window.open(url, '_blank', 'noopener,noreferrer');
  });
}

