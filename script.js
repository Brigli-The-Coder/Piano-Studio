// PIANO SOUND ENGINE (Web Audio API — synthesized, no audio
// files, no CDN, no external dependency, near-zero footprint)
// ==========================================================
let audioCtx = null;

function getAudioContext() {
  if (!audioCtx) {
    const AC = window.AudioContext || window.webkitAudioContext;
    audioCtx = new AC();
  }
  // Some browsers start contexts "suspended" until a user gesture.
  if (audioCtx.state === 'suspended') audioCtx.resume();
  return audioCtx;
}

// Standard piano note frequencies (Hz), 4th/5th octave range.
// Extend this map as needed — key = note name, value = frequency.
const NOTE_FREQUENCIES = {
  'C4': 261.63, 'C#4': 277.18,
  'D4': 293.66, 'D#4': 311.13,
  'E4': 329.63,
  'F4': 349.23, 'F#4': 369.99,
  'G4': 392.00, 'G#4': 415.30,
  'A4': 440.00, 'A#4': 466.16,
  'B4': 493.88,
  'C5': 523.25, 'C#5': 554.37,
  'D5': 587.33, 'D#5': 622.25,
  'E5': 659.25,
  'F5': 698.46, 'F#5': 739.99,
  'G5': 783.99
};

function playNote(frequency) {
  const ctx = getAudioContext();
  const now = ctx.currentTime;

  const osc = ctx.createOscillator();
  const gain = ctx.createGain();

  osc.type = 'triangle'; // softer, more piano-like than a raw sine/square
  osc.frequency.setValueAtTime(frequency, now);

  // Quick attack, natural decay — mimics a plucked/struck string envelope.
  gain.gain.setValueAtTime(0, now);
  gain.gain.linearRampToValueAtTime(0.25, now + 0.01);
  gain.gain.exponentialRampToValueAtTime(0.0001, now + 0.9);

  osc.connect(gain);
  gain.connect(ctx.destination);

  osc.start(now);
  osc.stop(now + 0.9);
}

// ==========================================================
// PIANO KEY DIVIDERS (interactive, real playable octave)
// One octave, C4 -> C5, with correct black keys in between.
// No auto-play/random "playing itself" anymore — keys sound
// only when the user actually presses them, like a real piano.
// ==========================================================
function buildPianoKeys() {
  // 8 white keys: C4 D4 E4 F4 G4 A4 B4 C5
  const WHITE_NOTES = ['C4', 'D4', 'E4', 'F4', 'G4', 'A4', 'B4', 'C5'];

  // Black key sits right after the white key at this index,
  // except after E (index 2) and after the last B->C (index 6 has one: A#).
  // Standard pattern within an octave: C C# D D# E F F# G G# A A# B (C)
  // So black keys occur after white index: 0(C#),1(D#),3(F#),4(G#),5(A#)
  const BLACK_AFTER_WHITE_INDEX = {
    0: 'C#4',
    1: 'D#4',
    3: 'F#4',
    4: 'G#4',
    5: 'A#4'
  };

  document.querySelectorAll('[data-piano]').forEach((container) => {
    container.innerHTML = '';
    const whiteWrap = document.createElement('div');
    whiteWrap.style.display = 'flex';
    whiteWrap.style.width = '100%';
    whiteWrap.style.height = '100%';
    whiteWrap.style.position = 'relative';
    container.appendChild(whiteWrap);

    const whites = [];
    WHITE_NOTES.forEach((note, i) => {
      const key = document.createElement('div');
      key.className = 'key';
      key.dataset.index = i;
      key.dataset.note = note;
      whiteWrap.appendChild(key);
      whites.push(key);
    });

    requestAnimationFrame(() => {
      const whiteWidth = whites[0].getBoundingClientRect().width;
      whites.forEach((w, i) => {
        const blackNote = BLACK_AFTER_WHITE_INDEX[i];
        if (blackNote) {
          const black = document.createElement('div');
          black.className = 'key black';
          black.style.left = w.offsetLeft + whiteWidth * 0.68 + 'px';
          black.style.width = whiteWidth * 0.62 + 'px';
          black.dataset.note = blackNote;
          whiteWrap.appendChild(black);
        }
      });
    });

    const press = (el) => {
      el.classList.add('pressed');
      setTimeout(() => el.classList.remove('pressed'), 160);

      const note = el.dataset.note;
      if (note && NOTE_FREQUENCIES[note]) {
        playNote(NOTE_FREQUENCIES[note]);
      }
    };

    whiteWrap.addEventListener('pointerdown', (e) => {
      if (e.target.classList.contains('key')) press(e.target);
    });
  });
}

